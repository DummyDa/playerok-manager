// Uses the browser tooling already installed by the parent project.
const { chromium } = require('../frontend/node_modules/playwright');
const assert = require('node:assert/strict');
const path = require('node:path');

(async () => {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:3180', { waitUntil: 'networkidle' });
  await page.locator('.gift-card').first().waitFor();
  assert(await page.locator('.gift-card').count() >= 20);
  await page.screenshot({ path: path.join(__dirname, 'data/desktop.png') });
  const images = await page.locator('.gift-image').evaluateAll(images => images.filter(i => i.getBoundingClientRect().top < innerHeight).map(i => ({ ok: i.complete && i.naturalWidth > 0, fallback: i.src.endsWith('/icon.svg') })));
  assert(images.length > 0 && images.every(i => i.ok && !i.fallback), 'Visible gift previews should load from MRKT');
  await page.locator('.favorite-button').first().click();
  await page.locator('#favorites').click();
  await page.waitForFunction(() => document.querySelectorAll('.gift-card').length === 1);
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.locator('#fav-count').textContent(), '1');
  await page.locator('#reset').click();
  await page.waitForFunction(() => document.querySelectorAll('.gift-card').length >= 20 && document.querySelector('#grid').getAttribute('aria-busy') === 'false');
  await page.locator('#search').fill('no-such-gift-zzzz');
  await page.locator('#empty').waitFor({ state: 'visible' });
  await page.locator('#empty-reset').click();
  await page.waitForFunction(() => document.querySelectorAll('.gift-card').length >= 20 && document.querySelector('#grid').getAttribute('aria-busy') === 'false');
  await page.locator('.card-open').first().click();
  await page.locator('#gift-dialog').waitFor({ state: 'visible' });
  await page.screenshot({ path: path.join(__dirname, 'data/detail.png') });
  await page.keyboard.press('Escape');
  await page.locator('#gift-dialog').waitFor({ state: 'hidden' });
  await page.locator('[data-filter=collection]').click();
  await page.getByRole('searchbox', { name: 'Поиск: Коллекция', exact: true }).fill('Toy Bear');
  await page.locator('.picker-option').filter({ hasText: /^Toy Bear$/ }).click();
  await page.waitForFunction(() => [...document.querySelectorAll('.gift-body h3')].every(e => e.textContent === 'Toy Bear') && document.querySelectorAll('.gift-card').length > 0);
  await page.locator('#reset').click();
  await page.waitForFunction(() => document.querySelectorAll('.gift-card').length >= 20 && document.querySelector('#grid').getAttribute('aria-busy') === 'false');
  await page.locator('#load-sentinel').scrollIntoViewIfNeeded();
  await page.waitForFunction(() => document.querySelectorAll('.gift-card').length >= 60);
  while (await page.locator('.gift-card').count() < 300) {
    const before = await page.locator('.gift-card').count();
    await page.locator('#load-sentinel').scrollIntoViewIfNeeded();
    await page.waitForFunction(n => document.querySelectorAll('.gift-card').length > n, before, { timeout: 45000 });
  }
  const allIds = await page.locator('.card-open').evaluateAll(buttons => buttons.map(b => b.dataset.id));
  assert.equal(new Set(allIds).size, allIds.length, 'Pages must not duplicate gifts');
  await page.locator('#search').fill('liberty figure');
  await page.waitForFunction(() => document.querySelectorAll('.gift-card').length > 0 && [...document.querySelectorAll('.gift-body h3')].every(e => e.textContent === 'Liberty Figure'), null, { timeout: 45000 });
  assert(await page.locator('#results').textContent() !== '0 предложений');
  await page.screenshot({ path: path.join(__dirname, 'data/liberty-figure.png') });
  await page.locator('#reset').click();
  await page.waitForFunction(() => document.querySelectorAll('.gift-card').length > 0 && ![...document.querySelectorAll('.gift-body h3')].every(e => e.textContent === 'Liberty Figure'));
  await page.setViewportSize({ width: 375, height: 900 });
  await page.reload({ waitUntil: 'networkidle' });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile must not overflow horizontally');
  await page.screenshot({ path: path.join(__dirname, 'data/mobile.png') });
  await page.locator('#catalog').scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(__dirname, 'data/mobile-catalog.png') });
  await page.locator('#filter-panel summary').click();
  assert(await page.locator('[data-filter=collection]').isVisible());
  await page.locator('#filter-panel summary').click();
  await page.locator('.card-open').first().click();
  assert(await page.evaluate(() => document.querySelector('#gift-dialog').scrollWidth <= innerWidth), 'Mobile dialog should fit viewport');
  await page.keyboard.press('Escape');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.setViewportSize({ width: 900, height: 375 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Landscape must not overflow');
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ ok: true, checks: ['real previews', 'favorites persistence', 'search', 'empty state', 'modal and Escape', 'collection filter', 'automatic pagination past 257 to 300 real gifts', 'no duplicates', 'Liberty Figure search across MRKT', '375px mobile', 'mobile filters', 'landscape', 'reduced motion'], pageErrors: errors }));
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
